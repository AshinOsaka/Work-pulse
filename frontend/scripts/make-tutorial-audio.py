"""Turn a tutorial's narration into MP3 voice-over with Piper (free, offline, open-source text-to-speech).

Run once per tutorial on a developer machine; the MP3 files and their durations are committed. Nothing is sent to
any online service. Voice: Piper "en_GB-cori-high" (dataset: public-domain LibriVox recordings).

    pip install piper-tts lameenc
    python scripts/make-tutorial-audio.py customer-systems path/to/en_GB-cori-high.onnx
"""

from __future__ import annotations

import json
import sys
import wave
from io import BytesIO
from pathlib import Path

import lameenc
from piper import PiperVoice

ROOT = Path(__file__).resolve().parent.parent


def main(slug: str, model: str) -> None:
    lines: list[str] = json.loads((ROOT / f"src/features/tutorials/content/{slug}-script.json").read_text("utf-8"))
    out_dir = ROOT / f"public/tutorials/{slug}"
    out_dir.mkdir(parents=True, exist_ok=True)
    voice = PiperVoice.load(model)
    durations: list[float] = []
    for i, text in enumerate(lines, start=1):
        buf = BytesIO()
        with wave.open(buf, "wb") as wav:
            voice.synthesize_wav(text, wav)
        buf.seek(0)
        with wave.open(buf, "rb") as wav:
            rate, channels, frames = wav.getframerate(), wav.getnchannels(), wav.getnframes()
            pcm = wav.readframes(frames)
        encoder = lameenc.Encoder()
        encoder.set_bit_rate(48)
        encoder.set_in_sample_rate(rate)
        encoder.set_channels(channels)
        encoder.set_quality(2)
        (out_dir / f"{i:02d}.mp3").write_bytes(encoder.encode(pcm) + encoder.flush())
        durations.append(round(frames / rate, 2))
        print(f"{i:02d}.mp3  {durations[-1]:.1f}s")
    (ROOT / f"src/features/tutorials/content/{slug}-durations.ts").write_text(
        "// Generated by scripts/make-tutorial-audio.py: length in seconds of each voice-over part.\n"
        f"export const DURATIONS = {json.dumps(durations)}\n",
        "utf-8",
    )


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
